"""Builds the signal-only Claude prompt. `prompt_news.py` reuses
`_build_data_sections` to build a second, web-search-aware variant on top of
the same underlying data. ai-analysis-prompt-logic.md documents the template.
"""
from __future__ import annotations

from datetime import date
from typing import List

from . import analytics as A
from .selection import Pick


def _sign(v: float) -> str:
    return "+" if v >= 0 else ""


# Below this many completed BUY->SELL round trips a ticker's win rate and
# expectancy are anecdotes (one lucky trade reads as "100% win rate"), so the
# prompt says so instead of printing them as if they were statistics.
MIN_TRADES_FOR_STATS = 5


def _perf(stats: A.TradeStats) -> str:
    if stats.total_trades == 0:
        return "trades=0"
    if stats.total_trades < MIN_TRADES_FOR_STATS:
        return f"trades={stats.total_trades} (too few to judge)"
    return (f"trades={stats.total_trades} wr={round(stats.win_rate)}% "
            f"exp={_sign(stats.expectancy)}{stats.expectancy:.1f}%")


def _trend(last: A.Row) -> str:
    if not last.regime or last.plus_di is None or last.minus_di is None:
        return "regime=? di=?"
    return f"regime={last.regime} di=+{last.plus_di:.0f}/-{last.minus_di:.0f}"


# Earnings further out than this are left out of the prompt; within it the
# report can gap the price whatever the trend says.
EARNINGS_HORIZON_DAYS = 14


def _earnings(last: A.Row, today: str) -> str:
    if not last.earnings:
        return "earn=-"
    days = (date.fromisoformat(last.earnings) - date.fromisoformat(today)).days
    if 0 <= days <= EARNINGS_HORIZON_DAYS:
        return f"earn=in {days}d"
    return "earn=-"


def _build_data_sections(all_data: A.AllData, today: str) -> str:
    """Everything the model needs to see before the response-format
    instructions: portfolio summary, signal changes, performance, snapshot
    table, forward-return effectiveness. Shared by every prompt variant."""
    tickers = list(all_data.keys())
    consensus = A.market_consensus(all_data)
    fwd = A.aggregate_forward_returns(all_data)
    snapshot = A.latest_snapshot(all_data)

    signal_changes: List[str] = []
    for r in snapshot:
        rows = all_data[r.ticker]
        if len(rows) >= 2:
            last, prev = rows[-1], rows[-2]
            if last.signal != prev.signal:
                signal_changes.append(f"{r.ticker}: {prev.signal}→{last.signal}")

    port_sim = A.portfolio_simulation(all_data)
    port_last = port_sim[-1] if port_sim else None
    if port_last:
        port_line = (
            f"Strategy {_sign(port_last.strategy)}{port_last.strategy:.1f}% vs "
            f"buy-and-hold {_sign(port_last.bah)}{port_last.bah:.1f}% (equal-weight across all tickers)"
        )
    else:
        port_line = "Portfolio simulation unavailable"

    snapshot_lines: List[str] = []
    for r in snapshot:
        rows = all_data[r.ticker]
        last = rows[-1]
        perf = _perf(A.trade_stats(rows))
        snapshot_lines.append(" | ".join([
            r.ticker.ljust(5),
            r.signal.ljust(4),
            "$" + f"{r.price:.2f}".rjust(8),
            f"streak={r.streak['signal']}×{r.streak['days']}d".ljust(14),
            f"period={_sign(r.period_change_pct)}{r.period_change_pct:.1f}%".ljust(14),
            "agree=" + f"{last.confidence:.0f}".rjust(3),
            "adx=" + f"{last.adx:.0f}".rjust(3),
            _trend(last),
            _earnings(last, today),
            perf,
        ]))
    snapshot_block = "\n".join(snapshot_lines)

    fwd_line = (
        f"BUY: {_sign(fwd['BUY']['avg'])}{fwd['BUY']['avg']:.3f}% (n={fwd['BUY']['count']}) | "
        f"SELL: {_sign(fwd['SELL']['avg'])}{fwd['SELL']['avg']:.3f}% (n={fwd['SELL']['count']}) | "
        f"HOLD: {_sign(fwd['HOLD']['avg'])}{fwd['HOLD']['avg']:.3f}% (n={fwd['HOLD']['count']})"
    )

    signal_changes_line = (
        f"Signal changes since yesterday: {', '.join(signal_changes)}"
        if signal_changes
        else "No signal changes since yesterday."
    )

    return f"""You are reviewing algorithmic stock signals generated by a systematic trading bot. Today is {today}.

How the signals work (trend-following, daily close data):
- BUY = price above its 200-day average (regime=UP), 20-day EMA above 50-day EMA, and +DI above -DI.
- SELL = trend broken: price below the 200-day average (regime=DOWN), or short-term trend and DI both turned down.
  It means "exit / stay out", not a prediction of how far the stock will fall.
- HOLD = long-term uptrend intact but short-term trend mixed.
- agree% = how many of 5 trend reads point the same way (20/60/100 = 3/4/5 of 5). It is NOT a win probability.
- ADX = trend strength regardless of direction; di=+X/-Y shows the direction (+DI vs -DI).
- earn=in Nd = next earnings report in N calendar days (earn=- when none within 14 days or unknown).
  The price can gap on the report in either direction; the trend signal cannot anticipate it.
- Backtests show this system's value is risk control (smaller drawdowns), not predicting which stocks beat
  the market: its BUY vs SELL forward returns are close to a coin flip. Frame conclusions accordingly.

Portfolio: {len(tickers)} tickers | BUY: {consensus['BUY']} | SELL: {consensus['SELL']} | HOLD: {consensus['HOLD']}
{signal_changes_line}

Portfolio performance (equal-weight simulation):
{port_line}

Current snapshot (ticker | signal | price | streak | period_return | agree% | ADX | regime/DI | earnings | completed trades, win rate, expectancy):
{snapshot_block}

Signal effectiveness — avg next-trading-day % return across all historical data:
{fwd_line}"""


def _picks_block(picks: List[Pick], empty: str) -> str:
    if not picks:
        return f"  (none — {empty})"
    return "\n".join(f"  - {p.ticker}: {'; '.join(p.why)}" for p in picks)


def build_prompt(all_data: A.AllData, today: str, picks: List[Pick], risks: List[Pick]) -> str:
    """picks/risks come from selection.select — the tickers are fixed by
    rule; the model writes the reasons and the two summary fields."""
    data_sections = _build_data_sections(all_data, today)

    return f"""{data_sections}

The tickers below were already selected by fixed rules from the snapshot above (the rule
hits are shown after each). Do not add, drop or reorder them — your job is to explain them.

topPicks (BUY tickers in an uptrend; "clean" = regime=UP, +DI at least 5 above -DI, ADX >= 20,
agree >= 60; "weak" falls short of one of those, as listed):
{_picks_block(picks, "no BUY ticker is in an uptrend with +DI above -DI")}

riskWatch (broken, weakening or unreliable trends, earnings soon):
{_picks_block(risks, "nothing flagged")}

Respond with ONLY this JSON object (no markdown fences, no text outside the JSON):
{{
  "generatedAt": "{today}",
  "marketSummary": "2-3 sentences on the overall signal environment — reference the BUY/SELL/HOLD split, whether the strategy is beating buy-and-hold, and any notable signal changes today",
  "topPicks": [{{"ticker": "TICK", "reason": "specific, data-backed reason in one sentence"}}],
  "riskWatch": [{{"ticker": "TICK", "reason": "specific, data-backed concern in one sentence"}}],
  "portfolioNote": "1-2 sentences on portfolio health, strategy vs buy-and-hold, or actionable guidance"
}}

Rules:
- topPicks and riskWatch: exactly the tickers listed above, in that order, one reason each.
  An empty list above means an empty array.
- A "weak" topPick's reason must say what it falls short on (e.g. ADX below 20 = weak trend
  strength). These are trends to follow, not forecasts of outperformance.
- A riskWatch reason should explain the rule hits with the ticker's figures (streak, regime,
  DI, agree%, ADX).
- If tickers that share a theme (e.g. several semiconductor names) are all SELL, say so in
  marketSummary or portfolioNote as one theme rather than as separate risks.
- Ignore win rate / expectancy for tickers marked "too few to judge" — never cite them as evidence.
- If a ticker you mention has earn=in Nd with N <= 7, say so in its reason (the trend read carries
  event risk until the report is out). Do not treat an upcoming report as bullish or bearish by itself.
- Be specific (ticker names, streak lengths, agree%, ADX, DI, % figures) and avoid overconfident language
  ("will rise", "guaranteed") — describe trend and risk, not certainty.
- Do not invent data not present above."""
